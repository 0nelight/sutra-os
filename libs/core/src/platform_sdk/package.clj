(ns platform-sdk.package
  (:require [clojure.java.io :as io]
            [clojure.pprint :as pprint]
            [platform-sdk.gen :as gen]))

(set! *warn-on-reflection* true)

(def version "0.1.0")

(defn runtime-coordinate
  [{:keys [git sha root]}]
  (cond
    (and git sha) {'sutra/core {:git/url git :git/sha sha :deps/root "libs/core"}}
    root          {'sutra/core {:local/root root}}
    :else
      (throw
       (ex-info "the generated project needs a runtime coordinate: {:root <path to core>} or {:git <url> :sha <sha>}"
                {:runtime {}}))))

(defn- edn-file
  [banner value]
  (str ";; AUTO-GENERATED by platform-sdk.package — do not edit by hand.\n"
       ";; " banner "\n"
       (with-out-str (pprint/pprint value))))

(defn deps-edn
  [runtime]
  (edn-file "The generated SDK as a project: clj -Sdeps or a :local/root away from any app."
            {:paths ["src"] :deps (runtime-coordinate runtime)}))

(defn manifest
  [{:keys [ns ontology fingerprint namespaces files]}]
  (edn-file "What this SDK was generated from — the pin `sdk verify` judges."
            {:ns ns
             :ontology ontology
             :fingerprint fingerprint
             :version (str version "+" fingerprint)
             :namespaces namespaces
             :files (vec (keys files))}))

(defn write!
  [schema-map {:keys [runtime package?] :as opts} dir]
  (let [{:keys [files] :as generated} (gen/generate schema-map opts)
        root (io/file dir)]
    (doseq [[path src] files]
      (let [f (io/file root "src" path)]
        (io/make-parents f)
        (spit f src)))
    (when package?
      (spit (io/file root "deps.edn") (deps-edn runtime))
      (spit (io/file root "sdk.edn") (manifest generated)))
    (assoc generated
           :dir (.getPath root)
           :version (str version "+" (:fingerprint generated))
           :written (cond-> (mapv #(str "src/" %) (keys files))
                      package? (into ["deps.edn" "sdk.edn"])))))

(defn stamped-fingerprint
  [path]
  (let [f (io/file path)
        candidates (cond
                     (.isDirectory f) (concat [(io/file f "sdk.edn")]
                                              (filter #(re-find #"\\.cljs?\$" (.getName ^java.io.File %))
                                                      (file-seq f)))
                     :else [f])]
    (some (fn [^java.io.File c]
            (when (.isFile c)
              (second (re-find #"(?:ontology-fingerprint|:fingerprint)\s+\"([0-9a-f]{16})\""
                               (slurp c)))))
          candidates)))
