(def wb (c/workbook {"Sheet1" [[-70000 -40000 -10000 "2008-01-01" -120000 0.10]
                               [12000  8000   2750   "2008-03-01" 39000   0.12]
                               [15000  9200   4250   "2008-10-30" 30000   "x"]
                               [18000  10000  3250   "2009-02-15" 21000]
                               [21000  12000  2750   "2009-04-01" 37000]
                               [26000  14500  nil    nil          46000]]}
                    {:functions (merge date/functions fin/functions) :config {:now 45292.5}}))

(defn- calc [f] (c/calculate wb f))

(defn- close? [expected f]
  (let [actual (calc f)]
    (if (number? expected) (approx= expected actual 1e-6) (= expected actual))))

(defmacro ^:private checks [& pairs]
  `(are [f# expected#] (close? expected# f#) ~@pairs))

