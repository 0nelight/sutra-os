(ns ent-lsp.python
  (:require [clojure.java.io :as io]
            [clojure.string :as str]
            [ent-lsp.jsonrpc :as rpc])
  (:import [java.io File]))

(def generated "# AUTO-GENERATED by sutra_platform_sdk.generate")
(def ^:private skip-dirs #{"node_modules" "__pycache__" "site-packages" "venv" "env"})
(def ^:private kind-class 7)
(def ^:private kind-value #{12 21})
(def ^:private resolve-timeout-ms 2000)

(def empty-index {:object-types #{} :members #{} :functions #{} :states #{}})

(defn- states-of [literal]
  (mapcat (fn [[_ v]] [(str \" v \") (str "'" v "'")]) (re-seq #"'([^']*)'" literal)))

(defn- read-line* [{:keys [cls model?] :as st} line]
  (if-let [[_ c base] (re-find #"^class (\w+)\((\w+)\)" line)]
    (cond-> (assoc st :cls c :model? (or (= base "OntologyObject") (= c "TypedActions")))
      (= base "OntologyObject") (update-in [:index :object-types] conj c))
    (let [[_ lit]  (re-find #"^\w+ = Literal\[(.*)\]" line)
          [_ attr] (re-find #"^    (\w+): " line)
          [_ fun]  (re-find #"^    def ([a-zA-Z]\w*)\(" line)]
      (cond
        lit                              (update-in st [:index :states] into (states-of lit))
        (and fun (= cls "TypedFunctions")) (update-in st [:index :functions] conj fun)
        (and model? (or attr fun))       (update-in st [:index :members] conj (or attr fun))
        :else                            st))))

(defn index-source
  [src]
  (:index (reduce read-line* {:index empty-index} (str/split-lines src))))

(defn merge-indexes [indexes] (apply merge-with into empty-index indexes))

(defn kind-of
  [index {:keys [label kind]}]
  (cond (and (= kind kind-class) ((:object-types index) label)) "object-type"
        (and (kind-value kind) ((:states index) label))         "state"
        ((:functions index) label)                              "function"
        ((:members index) label)                                ::resolve))

(defn classify
  [label doc]
  (let [head (or (some->> (str/split-lines doc)
                          (remove #(or (str/blank? %) (str/starts-with? % "```")))
                          first str/trim)
                 "")]
    (cond
      (or (str/starts-with? head (str label ": One["))
          (str/starts-with? head (str label ": Many["))) "link-type"
      (str/starts-with? head (str label ": Attr[")) "property"
      (and (str/starts-with? head (str "def " label "("))
           (str/includes? doc "-> SyncApplyActionResponse")) "action")))

(defn- doc-of [item]
  (let [d (:documentation item)]
    (or (if (map? d) (:value d) d) (:detail item) "")))

(defn describe [item kind]
  (cond-> item (and (map? item) kind) (assoc-in [:labelDetails :description] kind)))

(defn- python-files [^File dir]
  (mapcat (fn [^File f]
            (cond (.isDirectory f) (when-not (or (str/starts-with? (.getName f) ".")
                                                 (skip-dirs (.getName f)))
                                     (python-files f))
                  (str/ends-with? (.getName f) ".py") [f]))
          (.listFiles dir)))

(defn has-python? [root]
  (boolean (first (python-files (File. ^String root)))))

(defn- generated? [^File f]
  (with-open [r (io/reader f)]
    (str/starts-with? (or (.readLine ^java.io.BufferedReader r) "") generated)))

(defn rescan
  [cache roots]
  (into {}
        (for [^File f (mapcat #(python-files (File. ^String %)) roots)
              :let [path (.getPath f) mtime (.lastModified f)
                    [seen idx] (cache path)]
              :when (or (= seen mtime)
                        (try (generated? f) (catch java.io.IOException _ false)))]
          [path [mtime (if (= seen mtime) idx (index-source (slurp f)))]])))

(defn- send-py! [py msg] (rpc/write-message (:stdin py) msg))

(defn request!
  [py method params timeout-ms]
  (let [id (str "sutra/" (swap! (:ids py) inc)) p (promise)]
    (swap! (:state py) assoc-in [:own id] p)
    (try
      (send-py! py {:id id :method method :params params})
      (let [r (deref p timeout-ms ::timeout)] (when-not (= r ::timeout) r))
      (finally (swap! (:state py) update :own dissoc id)))))

(defn- current-index [py]
  (let [{:keys [cache]} (swap! (:state py) #(update % :cache rescan (:roots %)))]
    (merge-indexes (map second (vals cache)))))

(defn label-items
  [py result]
  (let [items    (vec (if (map? result) (:items result) result))
        index    (current-index py)
        kinds    (mapv #(kind-of index %) items)
        pending  (into {} (for [[i k] (map-indexed vector kinds) :when (= k ::resolve)]
                            [i (future (request! py "completionItem/resolve" (items i)
                                                 resolve-timeout-ms))]))
        deadline (+ (System/currentTimeMillis) resolve-timeout-ms)
        kind-at  (fn [i k]
                   (if (= k ::resolve)
                     (some->> (deref (pending i)
                                     (max 0 (- deadline (System/currentTimeMillis))) nil)
                              doc-of (classify (:label (items i))))
                     k))
        labeled  (into [] (map-indexed #(describe (items %1) (kind-at %1 %2))) kinds)]
    (if (map? result) (assoc result :items labeled) labeled)))

(defn- from-pyright [py send-client! on-exit]
  (try
    (loop []
      (when-let [msg (rpc/read-message (:stdout py))]
        (let [{:keys [id method]} msg
              st @(:state py)]
          (cond
            method (do (when id (swap! (:state py) update :asked conj id))
                       (send-client! msg))
            (contains? (:own st) id) (deliver (get-in st [:own id]) (:result msg))
            (contains? (:completions st) id)
              (do (swap! (:state py) update :completions disj id)
                  (future (send-client! (try (update msg :result #(label-items py %))
                                             (catch Throwable _ msg)))))
            (contains? (:resolves st) id)
              (do (swap! (:state py) update :resolves dissoc id)
                  (send-client! (update msg :result describe (get-in st [:resolves id]))))
            :else (send-client! msg)))
        (recur)))
    (finally
      (run! #(deliver % nil) (vals (:own @(:state py))))
      (on-exit))))

(defn start!
  [argv roots send-client! on-exit]
  (let [proc (.start (doto (ProcessBuilder. ^java.util.List argv)
                       (.redirectError java.lang.ProcessBuilder$Redirect/INHERIT)))
        py   {:proc   proc
              :stdin  (.getOutputStream proc)
              :stdout (.getInputStream proc)
              :ids    (atom 0)
              :state  (atom {:roots roots :cache {} :own {} :completions #{} :resolves {}
                             :asked #{}})}]
    (doto (Thread. ^Runnable #(from-pyright py send-client! on-exit)) (.setDaemon true) .start)
    py))

(defn forward!
  [py {:keys [id method params] :as msg}]
  (case method
    "textDocument/completion" (swap! (:state py) update :completions conj id)
    "completionItem/resolve"
      (when-let [k (get-in params [:labelDetails :description])]
        (swap! (:state py) assoc-in [:resolves id] k))
    nil (swap! (:state py) update :asked disj id)
    nil)
  (send-py! py msg))

(defn asked? [py id] (contains? (:asked @(:state py)) id))

(defn stop! [py] (.destroy ^Process (:proc py)))
