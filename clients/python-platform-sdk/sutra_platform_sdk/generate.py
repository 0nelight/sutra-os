from __future__ import annotations

import logging

from ._naming import kebab_to_pascal, kebab_to_snake, py_identifier
from .schema import (action_params, action_types, ambiguous_sides, attributes,
                     fingerprint, function_name, function_params, functions,
                     is_required, object_types, primary_key, sides)

PY_TYPES = {
    "string": "str", "text": "str", "keyword": "str", "uuid": "str",
    "boolean": "bool",
    "byte": "int", "short": "int", "integer": "int", "long": "int",
    "number": "Decimal", "decimal": "Decimal",
    "float": "float", "double": "float",
    "date": "datetime.date", "timestamp": "datetime.datetime",
    "instant": "datetime.datetime",
    "geopoint": "Any", "geoshape": "Any", "geohash": "str",
    "attachment": "Any", "media-reference": "Any",
    "timeseries": "Any", "vector": "Any", "marking": "str", "cipher": "str",
}

_HEADER = '''\
# AUTO-GENERATED by sutra_platform_sdk.generate — do not edit by hand.
# client SDK for the "{ontology}" ontology, fingerprint {fingerprint}.
from __future__ import annotations

import datetime
from decimal import Decimal
from typing import Any, Literal

from sutra_platform_sdk.actions import Actions, ActionConfig, SyncApplyActionResponse
from sutra_platform_sdk.functions import Functions
from sutra_platform_sdk.objects import Attr, Many, One, OntologyObject
from sutra_platform_sdk.predicates import Property, Link


def _oid(v):
    """An object parameter takes the object's id. Accept the object itself too —
    holding it is the normal case, and its business key is NOT an id."""
    return v.id if isinstance(v, OntologyObject) else v


def _wire(v):
    return v.isoformat() if isinstance(v, datetime.date) else v


__ontology__ = {ontology!r}
__ontology_fingerprint__ = {fingerprint!r}
'''


_log = logging.getLogger("sutra_platform_sdk.generate")


def py_type(declared) -> str:
    if isinstance(declared, (list, tuple)):
        declared = declared[0] if declared else None
    return PY_TYPES.get(str(declared), "Any")


def arg_type(declared) -> str:
    py = py_type(declared)
    if py == "Decimal":
        return "Decimal | float"
    if py.startswith("datetime."):
        return f"{py} | str"
    return py


def _literal(states) -> str:
    return "Literal[" + ", ".join(repr(str(x).lstrip(":")) for x in states) + "]"


def _lifecycles(ots: dict) -> dict:
    out = {}
    for spec in ots.values():
        lc = spec.get("lifecycle") or {}
        prop = str(lc.get("property") or "").lstrip(":")
        if prop and lc.get("states"):
            tname = spec["object-type-name"]
            out[(tname, prop)] = (kebab_to_pascal(tname) + kebab_to_pascal(prop),
                                  _literal(lc["states"]))
    return out


def _attr_opts(spec: dict) -> dict:
    return {a["attribute-name"]: a.get("opts") or {}
            for a in spec.get("attribute-list") or []}


def _attr_types(declared, opts: dict, is_pk: bool, alias) -> tuple:
    q = alias or arg_type(declared)
    v = alias or py_type(declared)
    if not (is_pk or is_required(opts) or opts.get("derived")):
        v = f"{v} | None"
    return v, q


def _unique(taken: dict, wire: str, owner: str, kind: str, skipped: list):
    ident = py_identifier(wire)
    if ident is None:
        skipped.append((owner, kind, wire, "no identifier can be spelled"))
        return None
    if ident in taken and taken[ident] != wire:
        skipped.append((owner, kind, wire,
                        f"{ident!r} is already {taken[ident]!r}"))
        return None
    taken[ident] = wire
    return ident


def _param_signature(params: list, object_types: set) -> tuple:
    sig, body = [], []
    for name, spec in params:
        spec = spec or {}
        declared = str(spec.get("type") or "")
        is_object = declared in object_types
        py = (f"{kebab_to_pascal(declared)} | str" if is_object
              else arg_type(spec.get("type")))
        if spec.get("multiple"):
            py = f"list[{py}]"
        arg = kebab_to_snake(name)
        value = f"_oid({arg})" if is_object else f"_wire({arg})"
        if is_required(spec):
            sig.append(f"{arg}: {py}")
            body.append(f"        args[{name!r}] = {value}")
        else:
            sig.append(f"{arg}: {py} | None = None")
            body.append(f"        if {arg} is not None:")
            body.append(f"            args[{name!r}] = {value}")
    return sig, body


_RESERVED = ("id", "title", "values", "around", "search_around",
             "objects", "where", "get", "all", "count", "aggregate")


def _action_on(spec: dict, object_types: set):
    on = str(spec.get("on") or "").lstrip(":")
    if on in object_types:
        return on
    refs = {str((p or {}).get("type") or "") for _, p in action_params(spec)
            if is_required(p)} & object_types
    return next(iter(refs)) if len(refs) == 1 and not on else None


def _bound_actions_source(schema: dict, tname: str, object_types: set,
                          members: dict, skipped: list) -> list:
    lines = []
    for name, spec in sorted(action_types(schema).items()):
        spec = spec or {}
        if _action_on(spec, object_types) != tname:
            continue
        params = action_params(spec)
        target = next((n for n, p in params if str((p or {}).get("type")) == tname), None)
        if target is None:
            continue
        method = _unique(members, str(name), tname, "action", skipped)
        if method is None:
            continue
        sig, body = _param_signature([(n, p) for n, p in params if n != target],
                                     object_types)
        tail = ["publish: bool = True", "action_config: ActionConfig | None = None"]
        lines.append(f"    def {method}(self, *, " + ", ".join(sig + tail)
                     + ") -> SyncApplyActionResponse:")
        doc = spec.get("description") or spec.get("display-name")
        if doc:
            lines.append(f"        {str(doc)!r}")
        lines.append(f"        args: dict[str, Any] = {{{str(target)!r}: self.id}}")
        lines.extend(body)
        lines.append(f"        return Actions(self._client)._invoke({str(name)!r}, args,")
        lines.append("            publish=publish, action_config=action_config)")
        lines.append("")
    return lines


def _actions_source(schema: dict, object_types: set) -> list:
    actions = action_types(schema)
    lines = ["class TypedActions(Actions):", '    """One method per action type.',
             "",
             "    Sutra-OS's action grammar is closed (`parser/ent.clj` ActionEntry), so a",
             "    parameter's `:required` flag and `:type` are facts, not conventions —",
             "    they become the signature. `:multiple` means the param carries a LIST",
             "    and one submit fans over each element.",
             '    """']
    if not actions:
        lines.append("    pass")
        lines.append("")
        return lines
    for name in sorted(actions):
        spec = actions[name] or {}
        params = action_params(spec)
        sig, body = _param_signature(params, object_types)
        method = kebab_to_snake(str(name))
        lines.append("")
        tail = ["publish: bool = True", "action_config: ActionConfig | None = None"]
        lines.append(f"    def {method}(self, *, " + ", ".join(sig + tail)
                     + ") -> SyncApplyActionResponse:")
        doc = spec.get("description") or spec.get("display-name")
        if doc:
            lines.append(f"        {str(doc)!r}")
        lines.append("        args: dict[str, Any] = {}")
        lines.extend(body)
        lines.append(f"        return self._invoke({str(name)!r}, args, publish=publish,")
        lines.append("                            action_config=action_config)")
    lines.append("")
    return lines


def _functions_source(schema: dict) -> list:
    fns = functions(schema)
    lines = ["class TypedFunctions(Functions):", '    """One method per function.',
             "",
             "    An edit function's `:param-types` is an annotation and is routinely",
             "    absent — the real parameter list only exists once the source compiles,",
             "    server-side — so an untyped function keeps a `**inputs` signature. No",
             "    function declares an OUTPUT type anywhere in the ontology, which is why",
             "    every return is `Any`.",
             '    """']
    named = sorted(((str(function_name(spec)), spec) for spec in fns
                    if function_name(spec)), key=lambda kv: kv[0])
    if not named:
        lines.append("    pass")
        lines.append("")
        return lines
    for name, spec in named:
        params = function_params(spec)
        method = kebab_to_snake(name)
        lines.append("")
        if params:
            sig = ", ".join(f"{kebab_to_snake(p)}: {py_type(t)} | None = None"
                            for p, t in params)
            lines.append(f"    def {method}(self, *, {sig}) -> Any:")
            lines.append("        inputs = {}")
            for p, _ in params:
                lines.append(f"        if {kebab_to_snake(p)} is not None:")
                lines.append(f"            inputs[{p!r}] = {kebab_to_snake(p)}")
        else:
            lines.append(f"    def {method}(self, **inputs) -> Any:")
            lines.append("        inputs = {k.replace('_', '-'): v for k, v in inputs.items()}")
        lines.append(f"        return self._run({name!r}, inputs)")
    lines.append("")
    return lines


def generate(schema: dict, out_path: str | None = None, ontology: str = "sutra",
             backing: dict | None = None) -> str:
    ots = object_types(schema)
    fp = fingerprint(schema)
    type_names = {s.get("object-type-name") for s in ots.values()}
    lines = [_HEADER.format(ontology=ontology, fingerprint=fp), ""]
    lifecycles = _lifecycles(ots)
    for alias, literal in sorted(lifecycles.values()):
        lines.append(f"{alias} = {literal}")
    if lifecycles:
        lines.extend(["", ""])
    class_names = []
    skipped: list = []

    for rid, spec in sorted(ots.items(), key=lambda kv: kv[1].get("object-type-name") or ""):
        tname = spec["object-type-name"]
        cls = kebab_to_pascal(tname)
        class_names.append(cls)
        attrs = attributes(spec)
        pk = primary_key(spec, backing)
        type_sides = sides(schema, rid)
        for side in ambiguous_sides(schema, rid):
            skipped.append((tname, "link side", side,
                            "two sides share the name — give the link "
                            "forward-api-name / reverse-api-name"))

        lines.append(f"class {cls}(OntologyObject):")
        lines.append(f"    __sutra_type__ = {tname!r}")
        lines.append(f"    __primary_key__ = {pk!r}")
        title = str(spec.get("title-key") or "").lstrip(":") or None
        if title:
            lines.append(f"    __title_key__ = {title!r}")
        lines.append("")
        lines.append("    class object_type:")
        body = False
        taken = {}
        for an, at in attrs:
            ident = _unique(taken, an, tname, "property", skipped)
            if ident is None:
                continue
            lines.append(f"        {ident} = Property({tname!r}, {an!r}, "
                         f"{str(at)!r})")
            body = True
        for side, info in type_sides.items():
            ident = _unique(taken, side, tname, "link side", skipped)
            if ident is None:
                continue
            lines.append(f"        {ident} = Link({tname!r}, {side!r}, {info['far_type']!r})")
            body = True
        if not body:
            lines.append("        pass")
        lines.append("")
        members = dict.fromkeys(_RESERVED, "(reserved)")
        for side, info in type_sides.items():
            ident = _unique(members, side, tname, "link", skipped)
            if ident is not None:
                far = info["far_type"]
                kind = "One" if info.get("cardinality") == "one" else "Many"
                lines.append(f"    {ident}: {kind}[{kebab_to_pascal(far)}] = "
                             f"{kind}({tname!r}, {side!r}, {far!r})")
        link_names = set(members)
        opts = _attr_opts(spec)
        for an, at in attrs:
            if py_identifier(an) in link_names - set(_RESERVED):
                continue
            ident = _unique(members, an, tname, "property", skipped)
            if ident is not None:
                o = opts.get(an) or {}
                alias = (lifecycles.get((tname, an)) or (None,))[0]
                v, q = _attr_types(at, o, an == pk, alias)
                lines.append(f"    {ident}: Attr[{v}, {q}] = "
                             f"Attr({tname!r}, {an!r}, {str(at)!r})")
                doc = o.get("description") or o.get("name")
                if doc:
                    lines.append(f"    {str(doc)!r}")
        lines.append("")
        lines.extend(_bound_actions_source(schema, tname, type_names, members, skipped))
        lines.append("")

    lines.extend(_actions_source(schema, type_names))
    lines.append("")
    lines.extend(_functions_source(schema))
    lines.append("")
    lines.append("OBJECT_TYPES = [" + ", ".join(class_names) + "]")
    lines.append("")
    lines.append("")
    lines.append("def verify(client):")
    lines.append('    """Live fingerprint vs the one this module was generated against.')
    lines.append("")
    lines.append("    Additive ontology changes are harmless — the old SDK just does not")
    lines.append("    know the new property. Renames and deletions are not, and nothing")
    lines.append("    downstream can tell the difference until a call fails. Returns")
    lines.append("    (ok, live_fingerprint).")
    lines.append('    """')
    lines.append("    from sutra_platform_sdk.schema import fingerprint")
    lines.append("    live = fingerprint(client.schema(refresh=True))")
    lines.append("    return live == __ontology_fingerprint__, live")
    lines.append("")
    lines.append("")
    lines.append("def register_all(client, *, verify_fingerprint: bool = True):")
    lines.append('    """Bind the typed classes, actions and functions onto `client`."""')
    lines.append("    if verify_fingerprint:")
    lines.append("        ok, live = verify(client)")
    lines.append("        if not ok:")
    lines.append("            raise RuntimeError(")
    lines.append("                f'ontology drift: this SDK was generated against '")
    lines.append("                f'{__ontology_fingerprint__}, the server now serves {live} — '")
    lines.append("                f'regenerate, or pass verify_fingerprint=False to proceed')")
    lines.append("    for k in OBJECT_TYPES:")
    lines.append("        k._sutra_client = client")
    lines.append("        client.ontology.objects.register(k)")
    lines.append("    client.ontology.actions = TypedActions(client)")
    lines.append("    client.ontology.functions = TypedFunctions(client)")
    lines.append("    return client")
    lines.append("")

    for owner, kind, wire, why in skipped:
        _log.error("skipped %s %s.%s — %s", kind, owner, wire, why)

    src = "\n".join(lines)
    if out_path:
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(src)
    return src


def generate_from_client(client, out_path: str, ontology: str | None = None) -> str:
    schema = client.schema(refresh=True)
    if ontology is None:
        ontology = (client.me() or {}).get("ontology", "sutra") if hasattr(client, "me") else "sutra"
    return generate(schema, out_path, ontology=ontology)


def generate_from_export(schema_path: str, out_path: str, ontology: str = "sutra") -> str:
    with open(schema_path, "rb") as f:
        raw = f.read()
    try:
        from .transport import _decode, from_wire
        data = from_wire(_decode(raw))
    except Exception:
        import json
        data = json.loads(raw.decode("utf-8"))
    schema = data.get("schema", data) if isinstance(data, dict) else data
    return generate(schema, out_path, ontology=ontology)
