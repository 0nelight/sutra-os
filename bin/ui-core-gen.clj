(require '[clojure.string :as str] '[clojure.java.io :as io])

(def root (.getCanonicalPath (io/file (or (System/getenv "SUTRA_ROOT") "."))))
(def vend (str root "/clients/frontend/vendor/blueprint-cljs/src/"))
(def out (io/file root "clients/frontend/src/sutra_ui/ui/core.cljs"))
(def marke ";; ── Kit ──")

(def offen
  (into (sorted-set)
        (concat (when (.exists out)
                  (map second (re-seq #"\[(blueprint-cljs\.[a-z0-9.-]+) :as" (slurp out))))
                *command-line-args*)))

(defn ns-file [n]
  (io/file vend (str (-> n (str/replace "-" "_") (str/replace "." "/")) ".cljs")))

(defn publics [n]
  (for [[_ kind priv nm]
        (re-seq #"(?m)^\((defn-|defn|def|defonce|defmulti)\s+(\^:private\s+|\^\{:private true\}\s+)?([^\s\]\)]+)"
                (slurp (ns-file n)))
        :when (and (not= kind "defn-") (nil? priv))]
    nm))

(def names (for [n offen p (sort (publics n))] [p n]))
(def doppelt (set (for [[p ns] (group-by first names) :when (> (count ns) 1)] p)))
(def core-namen #{"clone"})
(def extra ["[clojure.string :as str]" "[sutra.i18n.core :as i18n]"])
(defn al [n] (str "b-" (subs n (count "blueprint-cljs."))))

(def tail
  (let [s (when (.exists out) (slurp out))
        i (some-> s (str/index-of marke))]
    (if i (subs s i) (str marke "\n"))))

(spit out
      (str "(ns sutra-ui.ui.core\n"
           "  \"The one door to Blueprint (Frontend-Konzept E2): every Blueprint primitive under its own\n"
           "   name, generated by bin/ui-core-gen.clj; below the Kit mark the kit's own blocks.\n"
           "   Outside sutra-ui.ui.* no namespace loads blueprint-cljs.*; clj-kondo enforces it.\"\n"
           "  (:refer-clojure :exclude [" (str/join " " (sort core-namen)) "])\n"
           "  (:require " (str/join "\n            "
                             (concat extra (for [n offen] (str "[" n " :as " (al n) "]"))))
           "))\n\n"
           (str/join "\n" (for [[p n] names :when (not (doppelt p))]
                            (str "(def " p " " (al n) "/" p ")")))
           "\n\n" tail))
(println "ui.core:" (count offen) "Namespaces," (count (remove (comp doppelt first) names))
         "Namen; ausgelassen (doppelt):" (sort doppelt))
