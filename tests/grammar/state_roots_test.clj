(def ^:private state-root
  #"\(defonce\s+(?:\^\S+\s+)*([^\s()\[\]]+)\s+(?:;[^\n]*\n\s*)*(?:\^\{(?:[^\"}]|\"[^\"]*\")*\}\s*)?\((?:atom|ref|agent|periodic/slot)[\s)]")

(defn- state-roots []
  (for [r roots
        :let [d (io/file r)]
        :when (.isDirectory d)
        ^java.io.File f (file-seq d)
        :when (re-find #"\.clj[cs]?$" (.getName f))
        :let [p (str/replace (.getPath f) "\\" "/")]
        [_ n] (re-seq state-root (slurp f))]
    [p n]))

(deftest every-state-root-is-declared
  (doseq [k (state-roots)]
    (testing (str/join " " k)
      (is (#{:cache :process} (first (get declared k)))
          (str (str/join " " k) " holds state no declaration names — a :cache, a :process"
               " resource, or truth that belongs in a control table")))))

(deftest every-declaration-names-a-state-root
  (let [found (set (state-roots))]
    (doseq [k (keys declared)]
      (is (contains? found k) (str (str/join " " k) " is declared but holds no state now"
                                   " — remove its declaration")))))
